import { useEffect, useState } from 'react';
import { Capacitor } from '@capacitor/core';
import { useTheme } from '@/context/ThemeContext';
import { lockSystemBars, unlockSystemBars } from '@/lib/systemBars';
import {
  BRAND_HOUSE_PATHS,
  BRAND_MARK_BOX,
  BRAND_S_CENTERLINE,
  BRAND_S_PATH,
  BRAND_WORDMARK_PATH,
  BRAND_WORDMARK_VIEWBOX,
} from '@/components/brand/brandMarkData';

/** How long the finished logo stays on screen, then it fades out. */
const HOLD_MS = 2800;
const REDUCED_MOTION_HOLD_MS = 900;
const FADE_MS = 450;

const SPLASH_BG = '#0C3B2E';
const SPLASH_INK = '#FFF6E3';

/** Plays once per app launch (module scope lasts until the page or app is reloaded). */
let splashPlayed = false;

function shouldPlay(): boolean {
  if (splashPlayed) return false;
  if (Capacitor.isNativePlatform()) return true;
  // Preview in a normal browser with  https://your-site/?splash
  try {
    return new URLSearchParams(window.location.search).has('splash');
  } catch {
    return false;
  }
}

type Phase = 'show' | 'hide' | 'done';

/**
 * Animated launch screen: the house is sketched in stroke by stroke, the italic S is written on
 * like a pen stroke, then the wordmark fades in. Geometry comes from brandMarkData.ts, which is
 * generated by branding/icons/tools/generate_mark.py, so it always matches the app icon.
 */
export default function SplashScreen() {
  const { theme } = useTheme();
  const [phase, setPhase] = useState<Phase>(() => (shouldPlay() ? 'show' : 'done'));

  useEffect(() => {
    if (phase !== 'show') return;
    splashPlayed = true;
    // Light status bar icons over the dark green splash, whatever the app theme is.
    lockSystemBars('dark');
    const reduceMotion = window.matchMedia?.('(prefers-reduced-motion: reduce)').matches === true;
    const timer = window.setTimeout(() => setPhase('hide'), reduceMotion ? REDUCED_MOTION_HOLD_MS : HOLD_MS);
    return () => window.clearTimeout(timer);
  }, [phase]);

  useEffect(() => {
    if (phase !== 'hide') return;
    const timer = window.setTimeout(() => {
      setPhase('done');
      unlockSystemBars(theme);
    }, FADE_MS);
    return () => window.clearTimeout(timer);
  }, [phase, theme]);

  if (phase === 'done') return null;

  const box = BRAND_MARK_BOX;

  return (
    <div
      className={phase === 'hide' ? 'sk-splash sk-splash--out' : 'sk-splash'}
      style={{ background: SPLASH_BG }}
      role="img"
      aria-label="Saka Krib"
    >
      <svg
        className="sk-splash-mark"
        viewBox={`${box.x} ${box.y} ${box.width} ${box.height}`}
        aria-hidden="true"
        focusable="false"
      >
        <defs>
          {/* The S is revealed by a wide pen stroke travelling along its centre-line. */}
          <mask id="sk-s-reveal" maskUnits="userSpaceOnUse" x="0" y="0" width="1024" height="1024">
            <path
              className="sk-reveal"
              d={BRAND_S_CENTERLINE}
              pathLength={1}
              fill="none"
              stroke="#fff"
              strokeWidth={190}
              strokeLinecap="butt"
            />
          </mask>
        </defs>

        <g fill="none" stroke={SPLASH_INK} strokeOpacity={0.45} strokeWidth={9.5} strokeLinecap="round" strokeLinejoin="round">
          {BRAND_HOUSE_PATHS.map((d, i) => (
            <path key={i} className="sk-pencil" d={d} pathLength={1} style={{ animationDelay: `${150 + i * 32}ms` }} />
          ))}
        </g>

        <path d={BRAND_S_PATH} fill={SPLASH_INK} mask="url(#sk-s-reveal)" />
      </svg>

      <svg className="sk-splash-wordmark" viewBox={BRAND_WORDMARK_VIEWBOX} aria-hidden="true" focusable="false">
        <path d={BRAND_WORDMARK_PATH} fill={SPLASH_INK} />
      </svg>
    </div>
  );
}
